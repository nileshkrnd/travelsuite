function lines(
  a: { ledgerId: string; debit: number; credit: number; narration?: string },
  b: { ledgerId: string; debit: number; credit: number; narration?: string }
): VoucherLine[] {
  return [
    {
      id: `${a.ledgerId}_dr`,
      ledgerId: a.ledgerId,
      debit: a.debit,
      credit: a.credit,
      narration: a.narration ?? "",
    },
    {
      id: `${b.ledgerId}_cr`,
      ledgerId: b.ledgerId,
      debit: b.debit,
      credit: b.credit,
      narration: b.narration ?? "",
    },
  ];
}

